// Helper function: SQL Database Backup Generator
function generateDatabaseSqlBackup(mysqli $conn): string {
    $tables = [];
    $res = $conn->query("SHOW TABLES");
    if ($res) {
        while ($row = $res->fetch_row()) {
            $tables[] = $row[0];
        }
    }

    $return = "-- ========================================================\n";
    $return .= "-- IntelliWare WIMS - Complete Database Backup\n";
    $return .= "-- Generated On: " . date('Y-m-d H:i:s') . "\n";
    $return .= "-- Generated By: " . htmlspecialchars($_SESSION['Username'] ?? 'Admin') . "\n";
    $return .= "-- Server Version: " . $conn->server_info . "\n";
    $return .= "-- ========================================================\n\n";
    $return .= "SET FOREIGN_KEY_CHECKS=0;\nSET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n\n";

    foreach ($tables as $table) {
        $createRow = $conn->query("SHOW CREATE TABLE `$table`")->fetch_row();
        $return .= "--\n-- Structure for table `$table`\n--\n\n";
        $return .= "DROP TABLE IF EXISTS `$table`;\n";
        $return .= $createRow[1] . ";\n\n";

        $dataRes = $conn->query("SELECT * FROM `$table`");
        if ($dataRes && $dataRes->num_rows > 0) {
            $numFields = $dataRes->field_count;
            $return .= "--\n-- Dumping data for table `$table`\n--\n\n";
            while ($row = $dataRes->fetch_row()) {
                $return .= "INSERT INTO `$table` VALUES(";
                for ($j = 0; $j < $numFields; $j++) {
                    if (isset($row[$j])) {
                        $return .= "'" . $conn->real_escape_string($row[$j]) . "'";
                    } else {
                        $return .= "NULL";
                    }
                    if ($j < ($numFields - 1)) {
                        $return .= ",";
                    }
                }
                $return .= ");\n";
            }
            $return .= "\n";
        }
    }
    $return .= "SET FOREIGN_KEY_CHECKS=1;\n";
    return $return;
}

