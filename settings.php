document.addEventListener('DOMContentLoaded', function() {
    const tabs = document.querySelectorAll('.cfg-tab');
    const contents = document.querySelectorAll('.cfg-tab-content');

    function switchTab(tabId) {
        tabs.forEach(t => t.classList.remove('active'));
        contents.forEach(c => c.classList.remove('active'));

        const targetTab = document.querySelector(`.cfg-tab[data-tab="${tabId}"]`);
        const targetContent = document.getElementById(`tab-${tabId}`);

        if (targetTab && targetContent) {
            targetTab.classList.add('active');
            targetContent.classList.add('active');
            window.location.hash = tabId;
        }
    }

    tabs.forEach(tab => {
        tab.addEventListener('click', function() {
            const tabId = this.getAttribute('data-tab');
            switchTab(tabId);
        });
    });

    // Check URL hash on load
    const hash = window.location.hash.replace('#', '');
    if (hash && document.getElementById(`tab-${hash}`)) {
        switchTab(hash);
    }

    // Toggle API Key visibility in Vision tab
    const toggleVisionKeyBtn = document.getElementById('toggle-vision-key-btn');
    const visionKeyInput = document.getElementById('ai-vision-api-key-input');
    if (toggleVisionKeyBtn && visionKeyInput) {
        toggleVisionKeyBtn.addEventListener('click', function() {
            if (visionKeyInput.type === 'password') {
                visionKeyInput.type = 'text';
            } else {
                visionKeyInput.type = 'password';
            }
        });
    }

    // Test AI Connection button
    const testVisionBtn = document.getElementById('test-vision-conn-btn');
    const visionFeedback = document.getElementById('vision-test-feedback');
    if (testVisionBtn && visionKeyInput && visionFeedback) {
        testVisionBtn.addEventListener('click', function() {
            const key = visionKeyInput.value.trim();
            if (!key) {
                visionFeedback.className = 'p-3.5 rounded-xl border text-xs font-onest flex items-center gap-3 bg-amber-500/10 text-amber-300 border-amber-500/30';
                visionFeedback.innerHTML = '⚠️ Please enter an API key to test.';
                visionFeedback.classList.remove('hidden');
                return;
            }

            const btnText = document.getElementById('test-vision-btn-text');
            if (btnText) btnText.textContent = 'Testing Connection…';
            testVisionBtn.disabled = true;

            fetch('api/ai_extract_product.php', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ action: 'test_connection', api_key: key })
            })
            .then(r => r.json())
            .then(res => {
                testVisionBtn.disabled = false;
                if (btnText) btnText.textContent = 'Test AI Connection';
                visionFeedback.classList.remove('hidden');
                if (res.success) {
                    visionFeedback.className = 'p-3.5 rounded-xl border text-xs font-onest flex items-center gap-3 bg-[#10b981]/15 text-[#6ee7b7] border-[#10b981]/30';
                    visionFeedback.innerHTML = '🟢 ' + (res.message || 'Connected successfully! Google Gemini Vision is active and ready.');
                } else {
                    visionFeedback.className = 'p-3.5 rounded-xl border text-xs font-onest flex items-center gap-3 bg-red-500/15 text-red-300 border-red-500/30';
                    visionFeedback.innerHTML = '🔴 Connection failed: ' + (res.error || 'Unknown error');
                }
            })
            .catch(err => {
                testVisionBtn.disabled = false;
                if (btnText) btnText.textContent = 'Test AI Connection';
                visionFeedback.classList.remove('hidden');
                visionFeedback.className = 'p-3.5 rounded-xl border text-xs font-onest flex items-center gap-3 bg-red-500/15 text-red-300 border-red-500/30';
                visionFeedback.innerHTML = '🔴 Request error: ' + err.message;
            });
        });
    }
});
</script>

